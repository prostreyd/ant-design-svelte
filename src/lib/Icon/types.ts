import type { Component, Snippet } from 'svelte';
import type { HTMLAttributes } from 'svelte/elements';

/**
 * One node of a drawing: an element with its attributes and children. The shape is the one `@ant-design/icons-svg`
 * documents, declared here so that a definition from that package is assignable (structurally equal) while one file
 * only imports the package (`data.ts`).
 */
export interface AbstractNode {
  tag: string;
  attrs: Record<string, string>;
  children?: AbstractNode[];
}

/** The three themes of the Ant Design icon set. */
export type IconTheme = 'filled' | 'outlined' | 'twotone';

/**
 * The data of one drawing. A two-tone drawing is a function of the two colors; every other drawing is a plain node.
 */
export interface IconDefinition {
  /** The name of the drawing in kebab-case, without the theme: `account-book`. */
  name: string;
  theme: IconTheme;
  icon: AbstractNode | ((primaryColor: string, secondaryColor: string) => AbstractNode);
}

/** One color (the second is derived from it) or the pair `[primary, secondary]`. */
export type TwoToneColor = string | [string, string];

/** The props a custom `component` receives: it renders one `<svg>` and uses them on it. */
export interface IconComponentProps {
  width: string;
  height: string;
  fill: string;
  class?: string;
}

export type IconProps = Omit<HTMLAttributes<HTMLSpanElement>, 'children' | 'class' | 'style'> & {
  /** The data of one drawing, for example `StarOutlined` imported from `@ant-design/icons-svg`. */
  icon?: IconDefinition;
  /** A Svelte component that renders an `<svg>` (a custom drawing). */
  component?: Component<IconComponentProps>;
  /** Custom content (an `<svg>`); wins over `component` and `icon`. */
  children?: Snippet;
  /** Turns the icon once a second, endlessly. The `loading` drawing turns by default; `spin={false}` stops it. */
  spin?: boolean;
  /** Degrees, applied to the drawing (not to the wrapper that spins). */
  rotate?: number;
  /** Colors of a two-tone drawing: one color (the second is derived) or `[primary, secondary]`. */
  twoToneColor?: TwoToneColor;
  /**
   * The accessible name. By default the name of the drawing; `''` hides the icon from assistive technology
   * (a decorative icon next to visible text). A custom drawing has no name and is hidden unless `label` is set.
   */
  label?: string;
  /** Additional CSS class appended to the wrapper classes. */
  class?: string;
  /** Inline style of the wrapper. */
  style?: string;
};

/** The props of a ready icon component such as `StarOutlined`: everything but the drawing. */
export type NamedIconProps = Omit<IconProps, 'icon' | 'component' | 'children'>;

export interface IconFontOptions {
  /** The URL generated by an iconfont.cn project, or several: a later one overrides an earlier one for a name used twice. */
  scriptUrl?: string | string[];
  /** Props every icon of this font gets; the props of a single icon win. */
  extraCommonProps?: Record<string, unknown>;
}

export type IconFontProps = NamedIconProps & {
  /** The name of the symbol in the sprite, for example `icon-tuichu`. */
  type: string;
};
