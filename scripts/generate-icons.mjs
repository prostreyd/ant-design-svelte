// Writes the ready icon components, one per drawing of `@ant-design/icons-svg`, into `src/lib/Icon/icons/`, and the adapter
// `src/lib/Icon/data.ts`, the list of every drawing that the tests and the docs read (specs/icon.md, P8). The drawings are not copied: what is
// generated is a name and an import, and the MIT notice of the data travels with the dependency.
//
//   node scripts/generate-icons.mjs           writes the files (and removes the ones whose drawing left the package)
//   node scripts/generate-icons.mjs --check   fails if the files on disk differ from what would be written
//
// The files are committed and a test (tests/iconsGenerated.test.ts) compares them with `buildIcons()`.
import { existsSync, mkdirSync, readdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const HEADER = '<!-- Generated by scripts/generate-icons.mjs from @ant-design/icons-svg (MIT). Do not edit; run `npm run generate:icons`. -->';

/**
 * The text of one ready component. JavaScript with JSDoc, not TypeScript: 848 small files compile faster that way. It imports its own
 * drawing from its own ES file of the data package, with the extension (see `dataSource`), and nothing else of the package: a
 * development server loads this one file and not the other 847 (an import of all of them through one adapter made every page of
 * the browser tests ask for 848 more modules, and the library jobs of CI took twice as long).
 */
export function componentSource(name) {
  return `${HEADER}
<script>
  import Icon from '../Icon.svelte';
  import icon from '@ant-design/icons-svg/es/asn/${name}.js';

  /** @type {import('../types.js').NamedIconProps} */
  let props = $props();
</script>

<Icon {...props} {icon} />
`;
}

/** The barrel: every ready component by its name. */
export function barrelSource(names) {
  const lines = names.map((name) => `export { default as ${name} } from './${name}.svelte';`);
  return `// Generated by scripts/generate-icons.mjs from @ant-design/icons-svg (MIT). Do not edit; run \`npm run generate:icons\`.\n${lines.join('\n')}\n`;
}

/**
 * `data.ts`: every drawing of the package from its own ES file, with the extension, by its name. The components do not import it (each
 * imports its own drawing, so that a development server loads one file and not 848); it is the list that the tests, the docs and the
 * labs read the definitions from. From the package root (`import { StarOutlined } from '@ant-design/icons-svg'`) a drawing is not found
 * by Node before 24 (it sees the names of a CommonJS package only through a scan of the source, and finds two of the 851), so a server
 * render on Node 22 drew nothing; the ES files load natively on Node 22 and later and in every bundler, and each is a module of its own,
 * so a bundler keeps only the drawings that are imported (the package says `sideEffects: false`).
 */
export function dataSource(names) {
  const lines = names.map((name) => `export { default as ${name} } from '@ant-design/icons-svg/es/asn/${name}.js';`);
  return `// Generated by scripts/generate-icons.mjs from @ant-design/icons-svg (MIT). Do not edit; run \`npm run generate:icons\`.
/*
 * Every drawing of the icon data package, by its name, each from its own ES file with the extension. The ready icon components do not
 * import this file (each imports its own drawing, so that a development server loads one file and not 848): it is the list that the
 * tests and the documentation read the definitions from. A named import from the package root is not found by Node before 24 (a server
 * render on Node 22 drew nothing), while these files load natively on Node 22 and later and in every bundler.
 */
${lines.join('\n')}
`;
}

/**
 * The names of the drawings of the installed package and the files to write, keyed by the path under `src/lib/Icon/`.
 * @returns {Promise<{ names: string[], files: Record<string, string> }>}
 */
export async function buildIcons() {
  // The package is CommonJS: `default` is its `module.exports` on every Node, while the named exports of the namespace are found by
  // Node 24 but only two of them by Node 22.
  const namespace = await import('@ant-design/icons-svg');
  const data = namespace.default ?? namespace;
  const names = Object.keys(data)
    .filter((key) => /^[A-Z]\w*$/.test(key) && data[key] && typeof data[key].name === 'string' && typeof data[key].theme === 'string')
    .sort();
  /** @type {Record<string, string>} */
  const files = { 'data.ts': dataSource(names), 'icons/index.ts': barrelSource(names) };
  for (const name of names) files[`icons/${name}.svelte`] = componentSource(name);
  return { names, files };
}

async function main() {
  const base = fileURLToPath(new URL('../src/lib/Icon', import.meta.url));
  const { files } = await buildIcons();
  const check = process.argv.includes('--check');
  const existing = existsSync(`${base}/icons`) ? readdirSync(`${base}/icons`).map((file) => `icons/${file}`) : [];
  const stale = existing.filter((file) => !(file in files));
  const changed = Object.keys(files).filter((file) => !existsSync(`${base}/${file}`) || readFileSync(`${base}/${file}`, 'utf8') !== files[file]);
  const count = Object.keys(files).filter((file) => file.endsWith('.svelte')).length;
  if (check) {
    if (stale.length || changed.length) {
      console.error(`The icon components are out of date: ${changed.length} to write, ${stale.length} to remove. Run npm run generate:icons.`);
      process.exit(1);
    }
    console.log(`Icons: ${count} components are up to date.`);
    return;
  }
  mkdirSync(`${base}/icons`, { recursive: true });
  for (const file of changed) writeFileSync(`${base}/${file}`, files[file]);
  for (const file of stale) rmSync(`${base}/${file}`);
  console.log(`Icons: ${count} components, ${changed.length} files written, ${stale.length} removed.`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) await main();
